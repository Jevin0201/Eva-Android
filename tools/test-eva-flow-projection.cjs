'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),context=vm.createContext({console});
const files=['original-core.js','activity-core.js','statistics-core.js','disclosure-core.js','host.js'];
for(const file of files){
 const source=fs.readFileSync(path.join(root,'probe/assets/eva-native-transcript',file),'utf8');
 assert.equal(source,fs.readFileSync(path.join(root,'migration/eva-0.2.0-flow/native-transcript',file),'utf8'),file+' stays identical to migration snapshot');
 vm.runInContext(source,context,{filename:file});
}
vm.runInContext(fs.readFileSync(path.join(root,'probe/assets/eva-flow-projection.js'),'utf8'),context);
const {projectTurn,duration}=context.EvaFlowProjection;
const cmd=(id,status='completed')=>({id,type:'commandExecution',status,command:'echo test',exitCode:status==='failed'?1:0});
const final={id:'answer',type:'agentMessage',phase:'final_answer',text:'完成',status:'completed'};
const project=(items,status='completed',extra={})=>projectTurn({id:'test',status,items,...extra});
const block=t=>t.mobileBlocks.find(b=>b.kind==='assistant');
let result=block(project([cmd('a'),cmd('b'),final]));
assert.equal(result.workGroups.length,1,'continuous commands share an activity group');
assert.equal(result.workGroups[0].items.length,2);
assert.equal(result.collapsible,true);assert.equal(result.open,false);
assert.equal(result.durationMs,null,'no invented work duration');
result=block(project([cmd('a'),{id:'comment',type:'agentMessage',phase:'commentary',text:'下一步'},cmd('b'),final]));
assert.equal(result.workGroups.length,3,'commentary splits continuous tool runs');
assert.equal(result.workGroups[1].kind,'assistant-message');
result=block(project([cmd('a','failed'),cmd('b'),final]));
assert.equal(result.work[0].id,'a','failure remains in chronological position');
assert.equal(result.persistent.length,0,'ordinary failed tools follow desktop persistence policy');
assert.equal(result.failureCount,1);
result=block(project([{id:'approval',type:'mcpToolCall',server:'test',tool:'run',status:'failed',result:{type:'error',error:'MCP tool call requires approval, but approval policy is never'}},final]));
assert.equal(result.persistent[0].id,'approval','actionable policy failure remains outside collapsed work');
result=block(project([cmd('a','inProgress')],'inProgress'));
assert.equal(result.workGroups[0].state,'active');assert.equal(result.workGroups[0].label,'正在运行命令');
result=block(project([cmd('a'),final],'interrupted'));assert.equal(result.collapsible,false);assert.equal(result.open,true);
result=block(project([{id:'child',type:'subAgentActivity',agentThreadId:'child',agentPath:'/root/research',kind:'started'},cmd('a'),final]));
assert.equal(result.hasActiveAgents,true);assert.equal(result.open,true,'ongoing child cannot silently disappear into collapsed history');
result=block(project([{id:'child',type:'subAgentActivity',agentThreadId:'child',kind:'started'},{id:'end',type:'subAgentActivity',agentThreadId:'child',kind:'completed'},final]));
assert.equal(result.hasActiveAgents,false);assert.equal(result.open,false);
result=block(project([cmd('a'),final,cmd('post'),{...final,id:'second'}]));
assert.equal(result.finalGroups.length,3,'post-final activity and later answer preserved in original order');
assert.equal(result.finalGroups[1].items[0].id,'post');
const input={id:'privacy',status:'inProgress',items:[{id:'r',type:'reasoning',summary:[{text:'公开摘要'}],content:['private'],text:'private'},{id:'hidden',type:'dynamicToolCall',tool:'update_running_summary'}]};
const before=JSON.stringify(input),safe=projectTurn(input);
assert.equal(JSON.stringify(input),before,'adapter never mutates protocol input');
assert.equal(safe.items[0].content,undefined);assert.equal(safe.items[0].text,undefined);assert.equal(safe.items[0].summary[0],'公开摘要');
assert.equal(block(safe).work.length,1,'internal summary tool hidden');
assert.equal(duration({startedAtMs:100,completedAtMs:4300}),4200);
assert.equal(duration({startedAt:'2026-11-03T00:00:00Z',completedAt:'2026-11-03T00:01:02Z'}),62000);
assert.equal(duration({startedAtMs:100,completedAtMs:90}),null);
const key=block(project([cmd('stable'),final])).workGroups[0].key;
assert.equal(block(project([{id:'r',type:'reasoning',summary:[]},cmd('stable'),final])).workGroups[0].key,key,'streaming auxiliary updates preserve existing activity identity');
const steering=project([{id:'u',type:'userMessage'},cmd('a'),{id:'s',type:'steeringUserMessage'},cmd('b'),final]);
assert.equal(steering.mobileBlocks.map(b=>b.kind).join(','),'user,assistant,user,assistant');
console.log('Eva native transcript migration: browser-script load and behavioral assertions passed');
